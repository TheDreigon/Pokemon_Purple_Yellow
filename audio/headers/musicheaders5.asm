	channel 4, Music_PewterCity_Ch4

; Saffron City while Silph Co is still occupied -- the plain table entry.
;
; THREE channels, and the missing one is the point: there is no percussion in
; the occupied city. Beating Giovanni is what brings the drums in, so
; Music_SaffronFree below has four. Drumless is not unusual -- Cities2, Celadon
; and Pallet are all three-channel.
Music_SaffronCity::
	channel_count 3
	channel 1, Music_SaffronCity_Ch1
	channel 2, Music_SaffronCity_Ch2
	channel 3, Music_SaffronCity_Ch3

