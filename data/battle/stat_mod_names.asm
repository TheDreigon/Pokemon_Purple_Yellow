; Stats that move effects can raise or lower
; The relevant move effect IDs correspond to the stats

StatModTextStrings:
	list_start StatModTextStrings
	li "ATTACK"
	li "DEFENSE"
	li "SPEED"
	li "SPECIAL"
	assert_list_length SPECIAL_DOWN_SIDE_EFFECT - ATTACK_DOWN_SIDE_EFFECT + 1
	li "ACCURACY"
	li "EVASION"
	assert_list_length NUM_STAT_MODS - 2 ; two bytes are unused
	assert_list_length EVASION_UP1_EFFECT - ATTACK_UP1_EFFECT + 1
	assert_list_length EVASION_DOWN1_EFFECT - ATTACK_DOWN1_EFFECT + 1
	assert_list_length EVASION_UP2_EFFECT - ATTACK_UP2_EFFECT + 1
	assert_list_length EVASION_DOWN2_EFFECT - ATTACK_DOWN2_EFFECT + 1

; effects.asm turns an effect id into a stat-mod index by subtracting the
; ladder's first id (StatModifierUpEffect / StatModifierDownEffect, and the
; side-effect map "sub ATTACK_DOWN_SIDE_EFFECT"). Each ladder must therefore
; list the stats in MOD_* order, starting at MOD_ATTACK == 0.
ASSERT MOD_ATTACK == 0, "the stat-mod indexes start at 0: effects.asm adds (effect - ladder base) to wPlayerMonStatMods"
ASSERT DEFENSE_UP1_EFFECT - ATTACK_UP1_EFFECT == MOD_DEFENSE && SPEED_UP1_EFFECT - ATTACK_UP1_EFFECT == MOD_SPEED && SPECIAL_UP1_EFFECT - ATTACK_UP1_EFFECT == MOD_SPECIAL && ACCURACY_UP1_EFFECT - ATTACK_UP1_EFFECT == MOD_ACCURACY && EVASION_UP1_EFFECT - ATTACK_UP1_EFFECT == MOD_EVASION, "the +1 effect ladder must follow the MOD_* order"
ASSERT DEFENSE_DOWN1_EFFECT - ATTACK_DOWN1_EFFECT == MOD_DEFENSE && SPEED_DOWN1_EFFECT - ATTACK_DOWN1_EFFECT == MOD_SPEED && SPECIAL_DOWN1_EFFECT - ATTACK_DOWN1_EFFECT == MOD_SPECIAL && ACCURACY_DOWN1_EFFECT - ATTACK_DOWN1_EFFECT == MOD_ACCURACY && EVASION_DOWN1_EFFECT - ATTACK_DOWN1_EFFECT == MOD_EVASION, "the -1 effect ladder must follow the MOD_* order"
ASSERT DEFENSE_UP2_EFFECT - ATTACK_UP2_EFFECT == MOD_DEFENSE && SPEED_UP2_EFFECT - ATTACK_UP2_EFFECT == MOD_SPEED && SPECIAL_UP2_EFFECT - ATTACK_UP2_EFFECT == MOD_SPECIAL && ACCURACY_UP2_EFFECT - ATTACK_UP2_EFFECT == MOD_ACCURACY && EVASION_UP2_EFFECT - ATTACK_UP2_EFFECT == MOD_EVASION, "the +2 effect ladder must follow the MOD_* order"
ASSERT DEFENSE_DOWN2_EFFECT - ATTACK_DOWN2_EFFECT == MOD_DEFENSE && SPEED_DOWN2_EFFECT - ATTACK_DOWN2_EFFECT == MOD_SPEED && SPECIAL_DOWN2_EFFECT - ATTACK_DOWN2_EFFECT == MOD_SPECIAL && ACCURACY_DOWN2_EFFECT - ATTACK_DOWN2_EFFECT == MOD_ACCURACY && EVASION_DOWN2_EFFECT - ATTACK_DOWN2_EFFECT == MOD_EVASION, "the -2 effect ladder must follow the MOD_* order"
ASSERT DEFENSE_DOWN_SIDE_EFFECT - ATTACK_DOWN_SIDE_EFFECT == MOD_DEFENSE && SPEED_DOWN_SIDE_EFFECT - ATTACK_DOWN_SIDE_EFFECT == MOD_SPEED && SPECIAL_DOWN_SIDE_EFFECT - ATTACK_DOWN_SIDE_EFFECT == MOD_SPECIAL, "the -1 side-effect ladder must follow the MOD_* order"
